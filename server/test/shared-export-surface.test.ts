/**
 * Export-surface gate for `@devdigest/shared` (SPEC-16, AC-3).
 *
 * Ports are type-only exports, which no runtime test can see. This walks the
 * TypeScript program for `src/vendor/shared/index.ts` and compares the sorted
 * set of ALL exported names (values and types) to an inline literal. Moving
 * ports into `domain/ports` behind a type-only shim must leave this list
 * unchanged.
 */
const serverRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const entry = resolve(serverRoot, 'src/vendor/shared/index.ts');

function exportedNames(): string[] {
  const options: ts.CompilerOptions = {
    target: ts.ScriptTarget.ES2022,
    module: ts.ModuleKind.ESNext,
    moduleResolution: ts.ModuleResolutionKind.Bundler,
    strict: true,
    skipLibCheck: true,
    noEmit: true,
    types: ['node'],
    lib: ['lib.es2022.d.ts'],
  };
  const program = ts.createProgram([entry], options);
  const checker = program.getTypeChecker();
  const source = program.getSourceFile(entry);
  if (!source) throw new Error(`cannot load ${entry}`);
  const moduleSymbol = checker.getSymbolAtLocation(source);
  if (!moduleSymbol) throw new Error('index.ts has no module symbol');
  return checker
    .getExportsOfModule(moduleSymbol)
    .map((s) => s.getName())
    .sort();
}

