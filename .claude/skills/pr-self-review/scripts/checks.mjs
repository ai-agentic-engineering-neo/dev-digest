#!/usr/bin/env node
// Step 5 — deterministic checks (no LLM). Rules come from the root AGENTS.md.
//   node checks.mjs --static   fast: secrets, migrations, lockfiles, shared drift, wrapUntrusted candidates
//   node checks.mjs --build    slow: typecheck/lint/test of every touched package (run in background)
import { spawn, spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { git, repoRoot } from './lib/git.mjs';
import { matchesAny } from './lib/routing.mjs';
import { readJson, readLines, sha256, sha256File, statePaths, writeJson } from './lib/util.mjs';

const root = repoRoot();
const P = statePaths(root);
const manifest = readJson(P.manifest);
const live = manifest.files.filter((f) => !f.deleted);
const touched = (glob) => manifest.files.filter((f) => matchesAny(f.path, [glob]));

const finding = (check, severity, title, why, fix, extra = {}) => ({
  source: 'check',
  check,
  skill: `check:${check}`,
  severity,
  title,
  why,
  fix,
  file: null,
  line: null,
  ...extra,
});

const tail = (s, n = 40) => s.split('\n').slice(-n).join('\n').trim();

// ---------------------------------------------------------------- static
function staticChecks() {
  const findings = [];

  // Secrets: forbidden files + key patterns on changed lines. Matches are redacted in the report.
  const SECRET_FILES = ['**/.env', '**/.env.*', '**/secrets.json', '.claude/settings.local.json', '**/*.pem', '**/id_rsa', '**/id_ed25519'];
  const ALLOWED_FILES = ['**/.env.example', '**/.env.sample', '**/.env.template'];
  const SECRET_PATTERNS = [
    ['GitHub token', /\b(?:ghp|gho|ghu|ghs|ghr)_[A-Za-z0-9]{30,}\b|\bgithub_pat_[A-Za-z0-9_]{40,}\b/],
    ['OpenAI/OpenRouter/Anthropic key', /\bsk-(?:or-v1-|ant-|proj-)?[A-Za-z0-9_-]{32,}\b/],
    ['AWS access key', /\bAKIA[0-9A-Z]{16}\b/],
    ['Slack token', /\bxox[abprs]-[A-Za-z0-9-]{10,}\b/],
    ['private key', /-----BEGIN (?:RSA |EC |OPENSSH |DSA )?PRIVATE KEY-----/],
  ];
  for (const f of live) {
    if (matchesAny(f.path, SECRET_FILES) && !matchesAny(f.path, ALLOWED_FILES)) {
      findings.push(
        finding('secrets', 'CRITICAL', `Secret-bearing file in the diff: ${f.path}`,
          'Secrets never go to git — only through LocalSecretsProvider (~/.devdigest/secrets.json).',
          `Remove it from the change (git rm --cached ${f.path}) and add it to .gitignore.`, { file: f.path }),
      );
    }
    if (f.binary || f.ranges.length === 0) continue;
    const lines = readLines(path.join(root, f.path));
    if (!lines) continue;
    for (const [s, e] of f.ranges) {
      for (let i = s; i <= e; i++) {
        for (const [label, re] of SECRET_PATTERNS) {
          if (re.test(lines[i - 1] ?? '')) {
            findings.push(
              finding('secrets', 'CRITICAL', `Possible ${label} committed`,
                'A credential-shaped value appears on a changed line (value redacted). Secrets never go to git.',
                'Move it to ~/.devdigest/secrets.json via LocalSecretsProvider and rotate the credential if it was ever pushed.',
                { file: f.path, line: i }),
            );
          }
        }
      }
    }
  }

  // Generated migrations edited without a schema change.
  const migrations = touched('server/src/db/migrations/**');
  if (migrations.length && touched('server/src/db/schema/**').length === 0) {
    findings.push(
      finding('migrations', 'CRITICAL', 'Migration changed without a schema change',
        `server/src/db/migrations/* is generated by drizzle-kit, but ${migrations.length} migration file(s) changed while server/src/db/schema/ did not — a hand edit.`,
        'Revert the migration edits, change server/src/db/schema/, then run `pnpm db:generate` in server/.',
        { file: migrations[0].path }),
    );
  }

  // Lockfile edited without its package.json.
  for (const lock of ['server/pnpm-lock.yaml', 'client/pnpm-lock.yaml', 'reviewer-core/package-lock.json', 'e2e/package-lock.json']) {
    const pkg = path.posix.join(path.posix.dirname(lock), 'package.json');
    if (touched(lock).length && !touched(pkg).length) {
      findings.push(
        finding('lockfile', 'WARNING', `${lock} changed without ${pkg}`,
          'Lockfiles are never edited by hand; a lockfile-only change is usually an accidental reinstall with a different package manager version.',
          'Revert it, or regenerate with the pinned pnpm 10 / npm and explain why in the PR.', { file: lock }),
      );
    }
  }

  // @devdigest/shared copies must stay identical — only judged when the diff touches either copy.
  if (touched('server/src/vendor/shared/**').length || touched('client/src/vendor/shared/**').length) {
    const r = spawnSync(path.join(root, 'scripts', 'check-shared-drift.sh'), { cwd: root, encoding: 'utf8' });
    if (r.status !== 0) {
      findings.push(
        finding('shared-drift', 'CRITICAL', '@devdigest/shared copies differ',
          `A contract change must update both server/src/vendor/shared (canonical) and client/src/vendor/shared.\n${tail((r.stdout || '') + (r.stderr || ''), 30)}`,
          'Copy the server version over the client one (or port the change both ways), then re-run ./scripts/check-shared-drift.sh.',
          { file: 'client/src/vendor/shared' }),
      );
    }
  }

  // wrapUntrusted(): candidates only — the security reviewer confirms or dismisses them.
  const LLM_PATTERN = /\b(?:chat\.completions\.create|messages\.create|responses\.create|generateText|streamText|complete(?:Chat)?)\s*\(|\brole:\s*['"](?:system|user)['"]|\b(?:systemPrompt|userPrompt|prompt)\s*[:=]/;
  const candidates = [];
  for (const f of live) {
    if (!matchesAny(f.path, ['server/src/**/*.ts', 'reviewer-core/src/**/*.ts']) || matchesAny(f.path, ['**/*.test.ts'])) continue;
    const lines = readLines(path.join(root, f.path));
    if (!lines) continue;
    const usesWrap = lines.some((l) => l.includes('wrapUntrusted'));
    for (const [s, e] of f.ranges) {
      for (let i = s; i <= e; i++) {
        const l = lines[i - 1] ?? '';
        if (LLM_PATTERN.test(l)) candidates.push({ file: f.path, line: i, text: l.trim().slice(0, 200), file_uses_wrapUntrusted: usesWrap });
      }
    }
  }

  writeJson(P.checksStatic, { version: 1, fingerprint: manifest.fingerprint, findings, wrap_untrusted_candidates: candidates });
  console.log(`static checks: ${findings.length} finding(s) (${findings.filter((f) => f.severity === 'CRITICAL').length} CRITICAL), ${candidates.length} wrapUntrusted candidate(s)`);
  for (const f of findings) console.log(`  ${f.severity} [${f.check}] ${f.title}${f.file ? ` — ${f.file}${f.line ? `:${f.line}` : ''}` : ''}`);
  console.log(`→ ${P.checksStatic}`);
}

// ---------------------------------------------------------------- build
// What each package's checks depend on (server imports reviewer-core src; reviewer-core uses the server's shared copy).
const PACKAGES = {
  server: { deps: ['server', 'reviewer-core'], pm: 'pnpm' },
  client: { deps: ['client'], pm: 'pnpm' },
  'reviewer-core': { deps: ['reviewer-core', 'server/src/vendor/shared'], pm: 'npm' },
  e2e: { deps: ['e2e'], pm: 'npm' },
};

function stepsFor(pkg, dockerUp) {
  switch (pkg) {
    case 'server':
      return [
        { cmd: ['pnpm', 'typecheck'] },
        { cmd: ['pnpm', 'exec', 'vitest', 'run', '--exclude', '**/*.it.test.ts'] },
        dockerUp
          ? { cmd: ['pnpm', 'exec', 'vitest', 'run', '.it.test'] }
          : { cmd: ['pnpm', 'exec', 'vitest', 'run', '.it.test'], skip: 'Docker is not running — integration tests (*.it.test.ts) not run' },
      ];
    case 'client':
      return [{ cmd: ['pnpm', 'typecheck'] }, { cmd: ['pnpm', 'lint'] }, { cmd: ['pnpm', 'test'] }];
    case 'reviewer-core':
      return [{ cmd: ['npm', 'run', 'typecheck'] }, { cmd: ['npm', 'test'] }];
    case 'e2e':
      return [{ cmd: ['npm', 'run', 'typecheck'] }]; // e2e tests need the whole stack — CI runs them
    default:
      return [];
  }
}

function run(cmd, cwd) {
  return new Promise((resolve) => {
    const child = spawn(cmd[0], cmd.slice(1), { cwd, env: { ...process.env, CI: '1', FORCE_COLOR: '0' } });
    let out = '';
    const add = (d) => {
      out += d.toString();
      if (out.length > 400_000) out = out.slice(-200_000);
    };
    child.stdout.on('data', add);
    child.stderr.on('data', add);
    const timer = setTimeout(() => child.kill('SIGKILL'), 15 * 60 * 1000);
    child.on('error', (e) => {
      clearTimeout(timer);
      resolve({ exit: 127, out: e.message });
    });
    child.on('close', (code) => {
      clearTimeout(timer);
      resolve({ exit: code ?? 1, out });
    });
  });
}

function pkgKey(pkg) {
  const { deps } = PACKAGES[pkg];
  const diff = git(['diff', '--binary', '--no-color', '--no-ext-diff', manifest.base_sha, '--', ...deps], { cwd: root, encoding: 'buffer' });
  const untracked = manifest.files
    .filter((f) => f.untracked && deps.some((d) => f.path === d || f.path.startsWith(d + '/')))
    .map((f) => f.path + ':' + sha256File(path.join(root, f.path)));
  return sha256('build-v1', pkg, manifest.base_sha, diff, ...untracked);
}

async function buildChecks() {
  const changedPkgs = new Set(manifest.files.map((f) => f.path.split('/')[0]).filter((p) => PACKAGES[p]));
  if (touched('reviewer-core/**').length) changedPkgs.add('server');
  if (touched('server/src/vendor/shared/**').length) changedPkgs.add('reviewer-core');
  const dockerUp = spawnSync('docker', ['info'], { stdio: 'ignore', timeout: 10_000 }).status === 0;

  const results = await Promise.all(
    [...changedPkgs].sort().map(async (pkg) => {
      const key = pkgKey(pkg) + (dockerUp ? ':docker' : ':nodocker');
      const cacheFile = path.join(P.cache, `build-${sha256(key)}.json`);
      const cached = readJson(cacheFile, null);
      if (cached) return { ...cached, cached: true };
      const cwd = path.join(root, pkg);
      const steps = [];
      if (!fs.existsSync(path.join(cwd, 'node_modules'))) {
        steps.push({ cmd: 'install', ok: false, exit: null, tail: `${pkg}/node_modules is missing — run \`${PACKAGES[pkg].pm} install\` in ${pkg}/` });
      } else {
        for (const s of stepsFor(pkg, dockerUp)) {
          if (s.skip) {
            steps.push({ cmd: s.cmd.join(' '), ok: null, skipped: s.skip });
            continue;
          }
          const r = await run(s.cmd, cwd);
          steps.push({ cmd: s.cmd.join(' '), ok: r.exit === 0, exit: r.exit, tail: r.exit === 0 ? '' : tail(r.out) });
        }
      }
      const res = { package: pkg, steps };
      // Only green runs are cached: a failure may be environmental (deps, Docker) and must re-run.
      if (steps.every((s) => s.ok !== false)) writeJson(cacheFile, res);
      return { ...res, cached: false };
    }),
  );

  const findings = [];
  for (const r of results) {
    for (const s of r.steps) {
      if (s.ok === false) {
        findings.push(
          finding('build', 'CRITICAL', `${r.package}: \`${s.cmd}\` failed`,
            `Done = typecheck + test pass in every touched package (root AGENTS.md).\n${s.tail}`,
            `Fix the failure, then re-run \`${s.cmd}\` in ${r.package}/.`, { file: `${r.package}/` }),
        );
      } else if (s.skipped) {
        findings.push(finding('build', 'WARNING', `${r.package}: \`${s.cmd}\` not run`, s.skipped, 'Start Docker (./scripts/dev.sh --db-only) and re-run if this change touches the DB.', { file: `${r.package}/` }));
      }
    }
  }
  writeJson(P.checksBuild, { version: 1, fingerprint: manifest.fingerprint, packages: results, findings });
  for (const r of results) {
    console.log(`${r.package}${r.cached ? ' (cached)' : ''}: ${r.steps.map((s) => `${s.cmd} ${s.ok === true ? '✓' : s.ok === false ? '✗' : '–'}`).join(' · ')}`);
  }
  if (results.length === 0) console.log('build checks: no package touched');
  console.log(`build checks: ${findings.filter((f) => f.severity === 'CRITICAL').length} CRITICAL → ${P.checksBuild}`);
}

if (process.argv.includes('--static')) staticChecks();
else if (process.argv.includes('--build')) await buildChecks();
else {
  console.error('usage: checks.mjs --static | --build');
  process.exit(2);
}
